CREATE TABLE IF NOT EXISTS chat_conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
    title VARCHAR(400) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE IF NOT EXISTS chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
    conversation_id BIGINT NOT NULL REFERENCES chat_conversations(id) ON DELETE CASCADE,
    client_request_id UUID NOT NULL,
    sequence_no INTEGER NOT NULL CHECK (sequence_no > 0),
    role VARCHAR(10) NOT NULL CHECK (role IN ('user','assistant')),
    state VARCHAR(10) NOT NULL CHECK (state IN ('pending','completed','failed')),
    content TEXT,
    answer_status VARCHAR(30),
    error_code VARCHAR(60),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    pending_conversation_id BIGINT UNIQUE,
    UNIQUE (conversation_id, sequence_no),
    CHECK ((state = 'pending' AND role = 'assistant' AND pending_conversation_id IS NOT NULL AND pending_conversation_id = conversation_id)
        OR (state <> 'pending' AND pending_conversation_id IS NULL)),
    CHECK (state = 'completed' OR (content IS NULL AND answer_status IS NULL))
);
CREATE TABLE IF NOT EXISTS chat_citations (
    assistant_message_id BIGINT NOT NULL REFERENCES chat_messages(id) ON DELETE CASCADE,
    citation_id VARCHAR(3) NOT NULL,
    chunk_id VARCHAR(200) NOT NULL,
    document_id VARCHAR(200) NOT NULL,
    article_id VARCHAR(100) NOT NULL,
    document_title TEXT NOT NULL,
    article TEXT NOT NULL,
    clause TEXT,
    point TEXT,
    source_url TEXT NOT NULL,
    PRIMARY KEY (assistant_message_id, citation_id),
    UNIQUE (assistant_message_id, chunk_id)
);
CREATE TABLE IF NOT EXISTS chat_receipts (
    client_request_id UUID PRIMARY KEY,
    conversation_id BIGINT,
    user_message_id BIGINT,
    assistant_message_id BIGINT,
    fingerprint VARCHAR(64),
    state VARCHAR(10) NOT NULL CHECK (state IN ('pending','completed','failed','deleted')),
    response_snapshot TEXT,
    error_snapshot TEXT,
    logical_status INTEGER,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX IF NOT EXISTS chat_receipts_pending ON chat_receipts(state, created_at);
